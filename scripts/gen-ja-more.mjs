function esc(s) {
  return s.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
}

function formatItem(item) {
  const slots = item.slots.map((s) => `"${esc(s)}"`).join(", ");
  const vocab = item.vocab.map(([w, m]) => `["${esc(w)}", "${esc(m)}"]`).join(", ");
  return `        {
          zh: "${esc(item.zh)}",
          target: "${esc(item.target)}",
          slots: [${slots}],
          vocab: [${vocab}],
        }`;
}

function formatGroup(group) {
  const grammar = group.grammar.map((g) => `"${esc(g)}"`).join(", ");
  const items = group.items.map(formatItem).join(",\n");
  return `    {
      structure: "${esc(group.structure)}",
      grammar: [${grammar}],
      tips: "${esc(group.tips)}",
      items: [
${items},
      ],
    }`;
}

function formatScenario(groups) {
  return groups.map(formatGroup).join(",\n");
}

function formatFile(exportName, pack) {
  const sections = SCENARIOS.map((s) => `  ${s}: [\n${formatScenario(pack[s])},\n  ]`).join(",\n");
  return `import type { JaLevelPack } from "../load";

export const ${exportName}: JaLevelPack = {
${sections},
};
`;
}

function item(zh, target, slots, vocab) {
  return { zh, target, slots, vocab };
}

function group(structure, grammar, tips, items) {
  return { structure, grammar, tips, items };
}

// Helper: build 11 groups × 4 items = 44 per scenario from templates
function buildScenario(groupDefs) {
  if (groupDefs.length !== 11) throw new Error(`Expected 11 groups, got ${groupDefs.length}`);
  for (const g of groupDefs) {
    if (g.items.length !== 4) throw new Error(`Group "${g.structure}" has ${g.items.length} items`);
  }
  return groupDefs;
}

