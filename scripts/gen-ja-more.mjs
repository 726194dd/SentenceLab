function applyDedup(pack, used) {
  const counters = {};
  for (const s of SCENARIOS) {
    for (const g of pack[s] ?? []) {
      for (const it of g.items) {
        if (used.has(it.target)) {
          const alts = DEDUP_MAP[it.target];
          if (!alts) throw new Error(`No dedup alt for: ${it.target}`);
          counters[it.target] = (counters[it.target] ?? 0) + 1;
          const alt = alts[counters[it.target] - 1] ?? alts[alts.length - 1];
          Object.assign(it, alt);
        }
        if (used.has(it.target)) throw new Error(`Still duplicate after dedup: ${it.target}`);
        used.add(it.target);
      }
    }
  }
}

function countItems(pack) {
  const counts = {};
  for (const s of SCENARIOS) {
    counts[s] = (pack[s] ?? []).reduce((sum, g) => sum + g.items.length, 0);
  }
  return counts;
}

function extractTargets(content) {
  const targets = [];
  const re = /target:\s*"([^"]+)"/g;
  let m;
  while ((m = re.exec(content)) !== null) targets.push(m[1]);
  return targets;
}

function collectAllTargets(pack) {
  const targets = [];
  for (const s of SCENARIOS) {
    for (const g of pack[s] ?? []) {
      for (const it of g.items) targets.push(it.target);
    }
  }
  return targets;
}

